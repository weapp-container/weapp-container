function provider({ invoke = async () => undefined, close = async () => 'actual close' } = {}) {
  const program = new EventEmitter(), events = [], calls = [], pages = [], errors = []
  program.reLaunch = async function (route) {
    const page = { path: route.replace(/^\//, ''), pageId: pages.length + 1,
      async callMethod(...args) { calls.push({ receiver: this, args }); return invoke(...args) } }
    pages.push(page); return page
  }
  program.currentPage = async () => pages.at(-1); program.close = close
  const originals = { reLaunch: program.reLaunch, currentPage: program.currentPage, on: program.on, close: program.close }
  const collector = createCollector({ emit: event => events.push({ ...structuredClone(event), seq: events.length }) })
  collector.attach(program)
  const listen = () => { const listener = function (event) { assert.equal(this, program); errors.push(event.message) }; assert.equal(program.on('exception', listener), program); return listener }
  const run = async () => {
    let page = await program.reLaunch('/' + plan.route)
    for (const step of plan.steps) {
      if (step.kind === 'checkpoint') collector.checkpoint({ evidence: { id: step.id, route: plan.route, nodes: groups(step) } }, { session: program, page })
      else if (step.kind === 'reLaunch') page = await program.reLaunch('/' + step.route)
      else await page.callMethod(step.method, ...step.args)
    }
  }
  return { program, originals, events, calls, pages, errors, collector, listen, run }
}
