#!/usr/bin/env node
/** Build only the pure projection; application runtime/build admission is separate. */
import { spawn } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { resolve, relative, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = resolve(HERE, '../../..')
const args = process.argv.slice(2)
if (args.length !== 6 || args[0] !== '--cargo' || args[2] !== '--rustc' || args[4] !== '--wasm-bindgen') {
  throw new Error('Use --cargo <absolute-cargo> --rustc <absolute-rustc> --wasm-bindgen <absolute-tool>')
}
const [cargo, rustc, bindgen] = [args[1], args[3], args[5]].map(value => {
  if (!value.startsWith('/')) throw new Error('tool paths must be absolute')
  return value
})
const digest = value => createHash('sha256').update(value).digest('hex')
const artifact = async path => { const bytes = await readFile(path); return { path: relative(ROOT, path), bytes: bytes.length, sha256: digest(bytes) } }
const inputPaths = [resolve(ROOT, 'Cargo.toml'), resolve(ROOT, 'Cargo.lock'), resolve(ROOT, 'rust-toolchain.toml'),
  resolve(ROOT, '.cargo/config.toml'), resolve(ROOT, 'examples/hosts/conformance-desktop/src/observation.rs'),
  resolve(HERE, 'projection/Cargo.toml'), resolve(HERE, 'projection/Cargo.lock'), resolve(HERE, 'projection/src/lib.rs')]
async function addSources(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) await addSources(path)
    else if (/\.(?:rs|js|toml)$/.test(entry.name)) inputPaths.push(path)
  }
}
await addSources(resolve(ROOT, 'crates/container-core/src'))
await addSources(resolve(ROOT, 'crates/container-render-skia/src'))
inputPaths.push(resolve(ROOT, 'crates/container-core/Cargo.toml'), resolve(ROOT, 'crates/container-render-skia/Cargo.toml'))
inputPaths.sort()
const before = await Promise.all(inputPaths.map(artifact))
const logs = []
async function run(command, commandArgs, environment = process.env) {
  const parts = [], child = spawn(command, commandArgs, { cwd: ROOT, env: environment, stdio: ['ignore', 'pipe', 'pipe'] })
  for (const stream of [child.stdout, child.stderr]) stream.on('data', data => { parts.push(data); process.stdout.write(data) })
  const code = await new Promise((done, failed) => { child.once('error', failed); child.once('close', done) })
  logs.push({ command, args: commandArgs, exitCode: code, output: Buffer.concat(parts).toString('utf8') })
  if (code !== 0) throw new Error(`projection command failed: ${command}`)
}
await run(rustc, ['--version', '--verbose'])
await run(bindgen, ['--version'])
const remaps = [`--remap-path-prefix=${ROOT}=weapp-container`]
if (process.env.HOME) remaps.push(`--remap-path-prefix=${process.env.HOME}=developer-home`)
await run(cargo, ['build', '--manifest-path', resolve(HERE, 'projection/Cargo.toml'), '--target', 'wasm32-unknown-unknown',
  '--release', '--locked', '--offline'], { ...process.env, RUSTC: rustc,
  RUSTFLAGS: [process.env.RUSTFLAGS, ...remaps].filter(Boolean).join(' ') })
await mkdir(resolve(HERE, 'generated'), { recursive: true })
await run(bindgen, [resolve(HERE, 'projection/target/wasm32-unknown-unknown/release/weapp_conformance_web_projection_candidate.wasm'),
  '--target', 'web', '--out-dir', resolve(HERE, 'generated'), '--out-name', 'projection'])
const after = await Promise.all(inputPaths.map(artifact))
if (JSON.stringify(before) !== JSON.stringify(after)) throw new Error('projection source inputs changed while building; no successful candidate report')
const outputs = await Promise.all(['projection.js', 'projection_bg.wasm'].map(name => artifact(resolve(HERE, 'generated', name))))
const pin = outputs.find(value => value.path.endsWith('.wasm'))
await writeFile(resolve(HERE, 'generated/projection-pin.mjs'), `// Generated by build-projection.mjs; this pin identifies a pure query module.\nexport const PROJECTION_WASM_PIN = Object.freeze(${JSON.stringify({ bytes: pin.bytes, sha256: pin.sha256 }, null, 2)})\n`)
const report = { schemaVersion: 1, candidateOnly: true, notExecutionEvidence: true, status: 'built',
  root: ROOT, generatedAt: new Date().toISOString(), inputs: before, outputs,
  tools: await Promise.all([cargo, rustc, bindgen].map(artifact)), commands: logs }
await writeFile(resolve(HERE, 'projection-build.json'), `${JSON.stringify(report, null, 2)}\n`)
